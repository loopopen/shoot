func TestCleanKeepsOutputWhenDirIsNotDot(t *testing.T) {
	root := t.TempDir()
	t.Chdir(root)
	if err := os.Mkdir("model", 0o755); err != nil {
		t.Fatal(err)
	}

	keep := filepath.Join("model", "user.shootnew.go")
	perType := filepath.Join("model", "user.shootnew.user.go")
	otherAllInOne := filepath.Join("model", "other.shootnew.go")
	stale := filepath.Join("model", "notes.shootnew.go")
	outside := "user.shootnew.user.go"

	writeFile(t, keep, "// Code generated by \"shoot new -getset -file=user.go\"; DO NOT EDIT.\npackage model\n")
	writeFile(t, perType, "// Code generated by \"shoot new -getset -type=User\"; DO NOT EDIT.\npackage model\n")
	writeFile(t, otherAllInOne, "// Code generated by \"shoot new -getset -type=* ./model\"; DO NOT EDIT.\npackage model\n")
	writeFile(t, stale, "package model\n")
	writeFile(t, outside, "// Code generated by \"shoot new -getset -type=User\"; DO NOT EDIT.\npackage model\n")

	g := NewGeneratorBase("new", "")
	g.allInOneFile = "user.go"
	g.commonFlags = &CommonFlags{Dir: "./model"}

	if err := g.Clean(); err != nil {
		t.Fatal(err)
	}

	assertExists(t, keep)
	assertExists(t, otherAllInOne)
	assertExists(t, outside)
	assertAbsent(t, perType)
	assertAbsent(t, stale)
}

func writeFile(t *testing.T, name, body string) {
	t.Helper()
	if err := os.WriteFile(name, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func assertExists(t *testing.T, name string) {
	t.Helper()
	if _, err := os.Stat(name); err != nil {
		t.Fatalf("%s: %v", name, err)
	}
}

func assertAbsent(t *testing.T, name string) {
	t.Helper()
	_, err := os.Stat(name)
	if !os.IsNotExist(err) {
		t.Fatalf("%s still exists: %v", name, err)
	}
}
