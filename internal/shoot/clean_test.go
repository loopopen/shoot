package shoot

import (
	"os"
	"path/filepath"
	"testing"
)

func TestLoadPackagePanicsWhenSourceFileMissing(t *testing.T) {
	root := t.TempDir()
	t.Chdir(root)
	if err := os.WriteFile("go.mod", []byte("module example\n\ngo 1.24.0\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir("model", 0o755); err != nil {
		t.Fatal(err)
	}
	src := "package model\n\n//-go:generate go tool shoot new -getset -type=* ./model\n\ntype User struct {\n\tid string\n}\n"
	if err := os.WriteFile("model/user.go", []byte(src), 0o644); err != nil {
		t.Fatal(err)
	}

	g := NewGeneratorBase("new", "")
	g.commonFlags = &CommonFlags{
		CmdLine:   "shoot new -getset -type=* ./model",
		TypeNames: []string{"*"},
		Dir:       "./model",
	}
	defer func() {
		recovered := recover()
		if recovered == nil {
			t.Fatal("expected panic")
		}
		if _, err := os.Stat("model/.shootnew.go"); !os.IsNotExist(err) {
			t.Fatalf(".shootnew.go was written: %v", err)
		}
	}()
	g.LoadPackage()
}

